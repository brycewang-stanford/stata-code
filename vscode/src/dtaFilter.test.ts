const FIXTURES = path.join(__dirname, "..", "test-fixtures", "dta");

async function open(name: string): Promise<DtaReader> {
  const bytes = new Uint8Array(fs.readFileSync(path.join(FIXTURES, name)));
  return DtaReader.open(new BufferByteSource(bytes));
}

async function count(reader: DtaReader, expression: string): Promise<number> {
  const filter = compileFilter(expression, reader.meta);
  await filter.prepare?.(reader);
  let kept = 0;
  if (filter.columns.length === 0) {
    for (let obs = 1; obs <= reader.meta.nObs; obs++) if (filter.test([], obs)) kept += 1;
    return kept;
  }
  await reader.scan(filter.columns, (rows, start) => {
    rows.forEach((row, i) => {
      if (filter.test(row, start + i + 1)) kept += 1;
    });
  });
  return kept;
}

