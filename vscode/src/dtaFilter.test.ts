describe("time-series operators and abbreviations", () => {
  test("the tsset declaration is read from the file", async () => {
    assert.deepEqual((await open("panel118.dta")).meta.tsset, {
      timeVar: "year",
      panelVar: "firm",
      delta: 1,
    });
    assert.deepEqual((await open("ts118.dta")).meta.tsset, { timeVar: "t", panelVar: "", delta: 2 });
    assert.equal((await open("survey118.dta")).meta.tsset, undefined);
  });

  for (const [expected, expression] of PANEL_COUNTS) {
    test(`panel: count if ${expression}`, async () => {
      assert.equal(await count(await open("panel118.dta"), expression), expected);
    });
  }

  for (const [expected, expression] of SERIES_COUNTS) {
    test(`delta(2) series: count if ${expression}`, async () => {
      assert.equal(await count(await open("ts118.dta"), expression), expected);
    });
  }

  test("errors read as Stata's do", async () => {
    const panel = (await open("panel118.dta")).meta;
    assert.throws(() => compileFilter("L.sal > 100", panel), /sal ambiguous abbreviation/);
    assert.throws(() => compileFilter("sal > 100", panel), /sal ambiguous abbreviation/);
    assert.throws(() => compileFilter("L.nothere > 1", panel), /nothere not found/);
    assert.throws(() => compileFilter("L.code == 1", panel), /type mismatch/);
    const survey = (await open("survey118.dta")).meta;
    assert.throws(() => compileFilter("L.age > 1", survey), /time variable not set/);
  });

  test("an exact name wins over a longer one it abbreviates", async () => {
    // `sales` is both a variable and a prefix of `sales_index`
    const reader = await open("panel118.dta");
    assert.equal(await count(reader, "sales > 100"), await count(reader, "sales > 100 & sales_index > 0"));
  });

  test("a variable that merely looks like an operator still works", async () => {
    const reader = await open("survey118.dta");
    assert.equal(await count(reader, "id > 0"), 500);
    assert.equal(await count(reader, "id > 0 & .a > 1"), 500);
  });
});
